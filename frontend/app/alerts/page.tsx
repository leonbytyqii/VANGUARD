"use client";

import Link from "next/link";
import { useCallback, useEffect, useState } from "react";

import {
  EmptyState,
  ErrorState,
  Loading,
  PageHeader,
  Panel,
  Select,
  SeverityBadge,
  StatusBadge,
  Table,
  Td,
  TextInput,
} from "@/components/ui/primitives";
import { relativeTime, shortId } from "@/lib/format";
import { apiGet, ApiError, qs } from "@/services/api";

export interface Alert {
  id: string;
  title: string;
  description: string;
  severity: string;
  risk_score: number;
  status: string;
  source: string;
  host_name: string | null;
  user: string | null;
  alert_timestamp: string;
  mitre_technique_ids: string[];
  assigned_to_id: string | null;
  related_event_ids: string[];
  evidence: Record<string, unknown>;
}

export default function AlertsPage() {
  const [alerts, setAlerts] = useState<Alert[]>([]);
  const [status, setStatus] = useState("");
  const [severity, setSeverity] = useState("");
  const [host, setHost] = useState("");
  const [minScore, setMinScore] = useState("");
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      setAlerts(
        await apiGet<Alert[]>(
          `/v1/alerts${qs({ status, severity, host, min_risk_score: minScore, limit: 200 })}`
        )
      );
    } catch (err) {
      setError(err instanceof ApiError ? err.detail : "Failed to load alerts.");
    } finally {
      setLoading(false);
    }
  }, [status, severity, host, minScore]);

  useEffect(() => {
    void load();
  }, [load]);

  return (
    <div className="space-y-6">
      <PageHeader
        title="Alerts"
        subtitle="Generated by the detection engine and scored by the documented risk formula. Risk score is arithmetic and explainable — see docs/RISK_SCORING.md."
      />

      <Panel className="flex flex-wrap items-center gap-3">
        <Select
          label="Status"
          value={status}
          onChange={setStatus}
          options={[
            { value: "", label: "All" },
            { value: "new", label: "New" },
            { value: "triaged", label: "Triaged" },
            { value: "investigating", label: "Investigating" },
            { value: "escalated", label: "Escalated" },
            { value: "false_positive", label: "False positive" },
            { value: "closed", label: "Closed" },
          ]}
        />
        <Select
          label="Severity"
          value={severity}
          onChange={setSeverity}
          options={[
            { value: "", label: "All" },
            { value: "CRITICAL", label: "Critical" },
            { value: "HIGH", label: "High" },
            { value: "MEDIUM", label: "Medium" },
            { value: "LOW", label: "Low" },
            { value: "INFO", label: "Info" },
          ]}
        />
        <TextInput value={host} onChange={setHost} placeholder="Host" onEnter={load} />
        <TextInput value={minScore} onChange={setMinScore} placeholder="Min risk" type="number" onEnter={load} />
        <span className="ml-auto text-xs text-soc-muted">{alerts.length} shown</span>
      </Panel>

      {error && <ErrorState message={error} />}
      {loading && <Panel><Loading /></Panel>}

      {!loading && alerts.length === 0 && !error && (
        <Panel>
          <EmptyState
            title="No alerts match these filters"
            hint="Alerts are produced when a detection fires on ingested telemetry. Use the simulation lab to generate some."
          />
        </Panel>
      )}

      {!loading && alerts.length > 0 && (
        <Table head={["Severity", "Risk", "Title", "Host / User", "ATT&CK", "Status", "When", ""]}>
          {alerts.map((a) => (
            <tr key={a.id} className="hover:bg-soc-panel2/40">
              <Td>
                <SeverityBadge severity={a.severity} />
              </Td>
              <Td className="tabular-nums font-semibold">{a.risk_score}</Td>
              <Td>
                <div className="text-soc-text">{a.title}</div>
                <div className="mt-0.5 font-mono text-[11px] text-soc-muted">{shortId(a.id)}</div>
              </Td>
              <Td className="text-xs">
                <div className="font-mono">{a.host_name ?? "—"}</div>
                <div className="font-mono text-soc-muted">{a.user ?? "—"}</div>
              </Td>
              <Td className="text-xs">
                {a.mitre_technique_ids.length === 0 ? (
                  <span className="text-soc-muted">—</span>
                ) : (
                  <div className="flex flex-wrap gap-1">
                    {a.mitre_technique_ids.map((t) => (
                      <span key={t} className="rounded bg-soc-panel2 px-1.5 py-0.5 font-mono text-[10px] text-soc-muted">
                        {t}
                      </span>
                    ))}
                  </div>
                )}
              </Td>
              <Td>
                <StatusBadge status={a.status} />
              </Td>
              <Td className="whitespace-nowrap text-xs text-soc-muted">{relativeTime(a.alert_timestamp)}</Td>
              <Td>
                <Link href={`/alerts/${a.id}`} className="text-xs text-soc-accent hover:underline">
                  Open
                </Link>
              </Td>
            </tr>
          ))}
        </Table>
      )}
    </div>
  );
}
